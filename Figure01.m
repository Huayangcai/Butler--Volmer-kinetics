
%% figure01.m
% Golden competition state - tight SVG export
% R2025a+: exportgraphics directly exports tightly cropped SVG.
% R2020a-R2024b: crop figure before print -dsvg.

clear; close all; clc;

%% Common definitions
phi = (1 + sqrt(5))/2;
lnphi = log(phi);

fontName = 'Arial';
fontSize = 13;

fprintf('Golden ratio phi = %.8f\n', phi);
fprintf('1/phi = %.8f\n', 1/phi);
fprintf('ln(phi) = %.8f\n\n', lnphi);

%% Figure 1: Reference-point innovation
xi = linspace(-4, 4, 1200);
beta = tanh(xi);
m = 1 ./ cosh(xi);

beta_g = 1/sqrt(5);
m_g = 2/sqrt(5);

% Wider canvas to match the semicircle aspect ratio
f1 = figure('Color','w', 'Units','pixels', ...
    'Position',[80 80 1080 620], ...
    'PaperPositionMode','auto', ...
    'Renderer','painters');

ax1 = axes('Parent',f1, 'Units','pixels', ...
    'Position',[100 84 940 480], ...
    'PositionConstraint','innerposition');
hold(ax1,'on');

% Universal normalized master curve
plot(ax1, beta, m, 'k-', 'LineWidth', 2.8);

% Reference axes
plot(ax1, [-1.02 1.02], [0 0], ...
    'k-', 'LineWidth', 0.8);
plot(ax1, [0 0], [0 1.03], ...
    'k-', 'LineWidth', 0.8);

% Equilibrium state
plot(ax1, 0, 1, 's', 'MarkerSize', 10, ...
    'MarkerFaceColor',[0.25 0.25 0.25], ...
    'MarkerEdgeColor','k');

% Golden competition states
plot(ax1, beta_g, m_g, 'o', 'MarkerSize', 12, ...
    'MarkerFaceColor',[0.85 0.33 0.10], ...
    'MarkerEdgeColor','k');

plot(ax1, -beta_g, m_g, 'o', 'MarkerSize', 12, ...
    'MarkerFaceColor',[0.85 0.33 0.10], ...
    'MarkerEdgeColor','k');

% Guide lines
plot(ax1, [beta_g beta_g], [0 m_g], '--', ...
    'Color',[0.45 0.45 0.45], 'LineWidth',1.2);

plot(ax1, [-beta_g -beta_g], [0 m_g], '--', ...
    'Color',[0.45 0.45 0.45], 'LineWidth',1.2);

plot(ax1, [-beta_g beta_g], [m_g m_g], '--', ...
    'Color',[0.45 0.45 0.45], 'LineWidth',1.2);

% Direction arrows
idxL = find(xi > -1.25, 1);
idxR = find(xi >  1.05, 1);

quiver(ax1, beta(idxL), m(idxL), ...
    beta(idxL+15)-beta(idxL), ...
    m(idxL+15)-m(idxL), 0, ...
    'k', 'LineWidth',1.3, 'MaxHeadSize',2);

quiver(ax1, beta(idxR), m(idxR), ...
    beta(idxR+15)-beta(idxR), ...
    m(idxR+15)-m(idxR), 0, ...
    'k', 'LineWidth',1.3, 'MaxHeadSize',2);

%% Annotations
text(ax1, 0.03, 1.005, ...
    'Equilibrium: $\xi=0$', ...
    'Interpreter','latex', ...
    'FontSize',fontSize, ...
    'VerticalAlignment','bottom');

text(ax1, beta_g+0.035, m_g+0.025, ...
    {'Anodic Golden state', ...
     '$\xi=+\ln\phi$', ...
     '$(\beta,m)=(1/\sqrt{5},\,2/\sqrt{5})$'}, ...
    'Interpreter','latex', ...
    'FontSize',fontSize-1, ...
    'HorizontalAlignment','left', ...
    'VerticalAlignment','bottom');

text(ax1, -beta_g-0.035, m_g+0.025, ...
    {'Cathodic Golden state', ...
     '$\xi=-\ln\phi$', ...
     '$(\beta,m)=(-1/\sqrt{5},\,2/\sqrt{5})$'}, ...
    'Interpreter','latex', ...
    'FontSize',fontSize-1, ...
    'HorizontalAlignment','right', ...
    'VerticalAlignment','bottom');

text(ax1, 0, 0.13, ...
    {'Universal competition-state criterion:', ...
     '$|\xi|=\ln\phi$', ...
     '$\beta^2+m^2=1$'}, ...
    'Interpreter','latex', ...
    'FontSize',fontSize+1, ...
    'HorizontalAlignment','center', ...
    'VerticalAlignment','middle');

xlabel(ax1, ...
    'Signed dominance, $\beta=S/\mathcal{N}=\tanh\xi$', ...
    'Interpreter','latex', ...
    'FontSize',fontSize+1);

ylabel(ax1, ...
    'Normalized coexistence, $m=M/\mathcal{N}=\mathrm{sech}\xi$', ...
    'Interpreter','latex', ...
    'FontSize',fontSize+1);

%% Axes configuration
set(ax1, ...
    'FontName',fontName, ...
    'FontSize',fontSize, ...
    'LineWidth',1.1, ...
    'Box','off', ...
    'TickDir','out');

% Preserve the geometry of the semicircle
axis(ax1,'equal');

% Explicit limits with space for upper annotations
xlim(ax1,[-1.055 1.055]);
ylim(ax1,[0 1.075]);

xticks(ax1,-1:0.2:1);
yticks(ax1,0:0.1:1);

grid(ax1,'off');

% Do NOT call axis(ax1,'tight') here.
drawnow;

%% Export PDF, PNG and SVG
out = 'Figure01';

% PDF: vector and tightly cropped
exportgraphics(ax1,[out '.pdf'], ...
    'ContentType','vector', ...
    'BackgroundColor','white');

% PNG: high-resolution and tightly cropped
exportgraphics(ax1,[out '.png'], ...
    'Resolution',600, ...
    'BackgroundColor','white');

% SVG: select method according to MATLAB version
if ~verLessThan('matlab','25.1')
    % MATLAB R2025a and later
    exportgraphics(ax1,[out '.svg'], ...
        'ContentType','vector', ...
        'Padding','tight', ...
        'BackgroundColor','white');
else
    % MATLAB R2020a to R2024b
    % Resize figure to the actual axes content bounds.
    cropFigureForSVG(f1,ax1,6);

    set(f1,'PaperPositionMode','auto');
    print(f1,[out '.svg'],'-dsvg','-painters');
end

fprintf('Exported %s.{pdf,png,svg}\n',out);

%% Local function: crop the canvas for older MATLAB versions
function cropFigureForSVG(fig,ax,pad)

    drawnow;

    set(fig,'Units','pixels');
    set(ax,'Units','pixels', ...
        'PositionConstraint','innerposition');

    drawnow;

    % Bounding box including axis labels and tick labels
    if ~verLessThan('matlab','9.13')
        % MATLAB R2022b and later
        % More accurate for axes with constrained aspect ratios
        bbox = tightPosition(ax,'IncludeLabels',true);
    else
        % MATLAB R2020a to R2022a
        p = get(ax,'Position');
        t = get(ax,'TightInset');

        bbox = [p(1)-t(1), ...
                p(2)-t(2), ...
                p(3)+t(1)+t(3), ...
                p(4)+t(2)+t(4)];
    end

    p = get(ax,'Position');
    fp = get(fig,'Position');

    % New canvas size with minimal safety margin
    newSize = ceil(bbox(3:4) + 2*pad);

    % Shrink the canvas without changing the plot dimensions
    set(fig,'Position',[fp(1:2),newSize]);

    % Move the axes into the cropped canvas
    set(ax,'Position', ...
        [p(1:2)-bbox(1:2)+pad, p(3:4)]);

    drawnow;
end